/**
 * @brief  The application entry point.
 * @retval int
 */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_ADC1_Init();
  MX_TIM2_Init();
  MX_USART2_UART_Init();
  /* USER CODE BEGIN 2 */
  HAL_TIM_Base_Start_IT(&htim2);
  HAL_ADC_Start(&hadc1);
  uart2_rx_init();

  fsm_cmdParse_init();
  fsm_cmdParse_run(EVT_NONE);
  fsm_appCtrl_init();
  fsm_appCtrl_run(EVT_NONE);

  swTim_init(&led_tim, LED_PERIOD);
  swTim_clear(&led_pwm_tim);
  swTim_clear(&arq_tim);
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
    if (led_tim.flag)
    {
      HAL_GPIO_WritePin(LED_RED_GPIO_Port, LED_RED_Pin, GPIO_PIN_RESET);
      swTim_init(&led_pwm_tim, LED_PWM_DURATION);
      swTim_init(&led_tim, LED_PERIOD);
    }

    if (led_pwm_tim.flag)
    {
      HAL_GPIO_WritePin(LED_RED_GPIO_Port, LED_RED_Pin, GPIO_PIN_SET);
      swTim_clear(&led_pwm_tim);
    }

    const char *rx_msg = uart2_receive();
    if (rx_msg != NULL)
    {
      fsm_cmdParse_load_msg(rx_msg);
      fsm_cmdParse_run(EVT_MSG_RCVD);
    }
    else
    {
      fsm_cmdParse_run(EVT_NONE);
    }

    if (app_evt != EVT_NONE)
    {
      sys_event evt = app_evt;
      app_evt = EVT_NONE;
      fsm_appCtrl_run(evt);
    }

    if (arq_tim.flag)
    {
      swTim_clear(&arq_tim);
      fsm_appCtrl_run(EVT_TIMEOUT);
    }
    __WFI();
  }
  /* USER CODE END 3 */
}

