void swTim_init(swTim_t *timer, uint16_t duration)
{
  if (timer == NULL)
    return;
  timer->flag = false;
  timer->duration = duration;
  timer->counter = (duration / TIM2_TICK);
}

void swTim_clear(swTim_t *timer)
{
  if (timer == NULL)
    return;
  timer->flag = false;
  timer->duration = 0;
  timer->counter = 0;
}
